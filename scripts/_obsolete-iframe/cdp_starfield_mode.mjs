import { writeFileSync } from "node:fs";
import { setTimeout as sleep } from "node:timers/promises";
const targets = await (await fetch("http://127.0.0.1:9223/json")).json();
const page = targets.find((t) => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let id = 0; const pending = new Map(); const errors = [];
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(new Error(JSON.stringify(m.error))) : p.resolve(m.result); return; } if (m.method === "Runtime.exceptionThrown") errors.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text); };
const send = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n, { resolve, reject }); ws.send(JSON.stringify({ id: n, method, params })); });
const evalJs = async (expression, userGesture = false) => { const r = await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true, userGesture }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result?.value; };
await send("Page.enable"); await send("Runtime.enable"); await send("Network.enable"); await send("Network.clearBrowserCache");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: "http://127.0.0.1:8787/" });
await sleep(4500);
await evalJs(`document.querySelector('#starfieldBtn').click()`, true);
await sleep(3500);
console.log("frame:", await evalJs(`(() => {
  const f = document.querySelector('#starfieldFrame');
  const d = f.contentDocument;
  return { src: f.getAttribute('src'), title: d?.title, navs: d ? [...d.querySelectorAll('.nav')].map(x=>x.textContent.trim()) : [], rail: d ? d.querySelector('.rail')?.getBoundingClientRect().width : null };
})()`));
console.log("rail hidden before:", await evalJs(`document.querySelector('#starfieldFrame').contentDocument.body.classList.contains('rail-hidden')`));
await evalJs(`document.querySelector('#starfieldFrame').contentDocument.querySelector('#railToggle').click()`, true);
await sleep(500);
console.log("rail hidden after:", await evalJs(`(() => {
  const d = document.querySelector('#starfieldFrame').contentDocument;
  return { hidden: d.body.classList.contains('rail-hidden'), railWidth: d.querySelector('.rail').getBoundingClientRect().width, stageLeft: getComputedStyle(d.querySelector('.stage')).left, showBtn: getComputedStyle(d.querySelector('#railShow')).display };
})()`));
const { data } = await send("Page.captureScreenshot", { format: "png" });
writeFileSync("D:/数据/deepseek-harness/default-workspace/music-hub/_shots/55-starfield-mode-hidden.png", Buffer.from(data, "base64"));
console.log("shot 55");
await evalJs(`document.querySelector('#starfieldFrame').contentDocument.querySelector('#railShow').click()`, true);
await sleep(300);
console.log("rail restored:", await evalJs(`document.querySelector('#starfieldFrame').contentDocument.body.classList.contains('rail-hidden')`));
await evalJs(`document.querySelector('#closeStarfield').click()`, true);
await sleep(500);
console.log("closed:", await evalJs(`({ open: document.querySelector('#starfieldOverlay').classList.contains('open'), src: document.querySelector('#starfieldFrame').getAttribute('src') })`));
console.log("errors:", errors.slice(0, 6));
ws.close(); process.exit(0);
