import { writeFileSync } from "node:fs";
const t = await (await fetch('http://127.0.0.1:9333/json/list')).json();
const p = t.find(x => x.type === 'page');
const ws = new WebSocket(p.webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0; const w = new Map(); const errors = [];
ws.onmessage = e => { const m = JSON.parse(e.data); if (w.has(m.id)) { w.get(m.id)(m.result); w.delete(m.id); } if (m.method === 'Runtime.exceptionThrown') errors.push(m.params.exceptionDetails.exception?.description || m.params.exceptionDetails.text); };
const send = (method, params = {}) => new Promise(res => { const n = ++id; w.set(n, res); ws.send(JSON.stringify({ id: n, method, params })); });
const ev = async (expr) => (await send('Runtime.evaluate', { expression: expr, returnByValue: true, awaitPromise: true, userGesture: true })).result?.value;
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
await send('Runtime.enable'); await send('Page.enable');
await send('Network.setCacheDisabled', { cacheDisabled: true });
await send('Page.reload', { ignoreCache: true });
await sleep(5000);
await ev(`document.querySelector('[data-tab="playlists"]').click()`);
await sleep(2500);
await ev(`(() => { const r = [...document.querySelectorAll('.pl-row')].find(x => x.querySelector('.pl-cover.nd')); if (r) r.click(); return !!r; })()`);
await sleep(3500);
console.log(await ev(`({ label: document.querySelector('#listLabel').textContent, rows: document.querySelectorAll('.track').length, first: document.querySelector('.track .t')?.textContent })`));
const shot = await send('Page.captureScreenshot', { format: 'png' });
writeFileSync('_shots/151-netease-playlists.png', Buffer.from(shot.data, 'base64'));
console.log('shot 151', 'errors', errors.slice(0,2));
ws.close(); process.exit(0);
