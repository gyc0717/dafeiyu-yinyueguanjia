import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { setTimeout as sleep } from "node:timers/promises";
import { fileURLToPath } from "node:url";
const OUT = fileURLToPath(new URL("../_shots/", import.meta.url));
const targets = await (await fetch("http://127.0.0.1:9223/json")).json();
const page = targets.find((t) => t.type === "page");
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { const p = pending.get(m.id); pending.delete(m.id); m.error ? p.reject(new Error(JSON.stringify(m.error))) : p.resolve(m.result); } };
const send = (method, params = {}) => new Promise((resolve, reject) => { const n = ++id; pending.set(n, { resolve, reject }); ws.send(JSON.stringify({ id: n, method, params })); });
const evalJs = async (expression, userGesture = false) => { const r = await send("Runtime.evaluate", { expression, returnByValue: true, awaitPromise: true, userGesture }); if (r.exceptionDetails) throw new Error(r.exceptionDetails.text); return r.result?.value; };
await send("Page.enable"); await send("Runtime.enable");
await send("Emulation.setDeviceMetricsOverride", { width: 1440, height: 900, deviceScaleFactor: 1, mobile: false });
await send("Page.navigate", { url: "http://127.0.0.1:8787/" });
await sleep(5000);
await evalJs(`document.querySelector('[data-tab="playlists"]').click()`, true);
await sleep(2200);
console.log(await evalJs(`({ remote: __mh.state.remotePlaylists.length, local: __mh.state.playlists.length, rows: document.querySelectorAll('.pl-row.remote').length, count: document.querySelector('#playlistCount')?.textContent, sections: [...document.querySelectorAll('.pl-section')].map(x=>x.textContent.trim()) })`));
const { data } = await send("Page.captureScreenshot", { format: "png" });
writeFileSync(join(OUT, "43-qq-playlists-auto.png"), Buffer.from(data, "base64"));
console.log("shot 43");
ws.close(); process.exit(0);
